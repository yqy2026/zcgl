@pytest.fixture
def isolated_fee_database():
    """Create and remove only the schema generated by this fixture."""
    schema = f"fee_race_{uuid4().hex}"
    assert re.fullmatch(r"fee_race_[0-9a-f]{32}", schema)
    url = os.environ["TEST_DATABASE_URL"]
    admin = create_engine(url)
    with admin.begin() as connection:
        connection.execute(text(f'CREATE SCHEMA "{schema}"'))
    engine = create_engine(
        url,
        connect_args={
            "options": f"-csearch_path={schema} -clock_timeout=30000 -cstatement_timeout=30000",
            "application_name": schema,
        },
        pool_size=5,
    )
    try:
        Base.metadata.create_all(engine)
        with engine.connect() as connection:
            assert connection.scalar(text("SELECT current_schema()")) == schema
        with Session(engine, expire_on_commit=False) as session:
            actor = User(
                id=str(uuid4()),
                username=f"race-{uuid4().hex}",
                phone=f"13{uuid4().int % 10**9:09d}",
                full_name="并发验证",
                password_hash="unused",
                account_type="service",
                is_active=True,
            )
            session.add(actor)
            session.commit()
            facts = _seed_fee_sources(session, actor.id)
            statement = session.get(ManagementFeeStatement, facts["statement_id"])
            document = Attachment(
                id=str(uuid4()),
                owner_type="management_fee_statement",
                owner_id=statement.id,
                file_name="stamp.png",
                file_type="png",
                file_size=1,
                storage_key="isolated/stamp.png",
                created_by=actor.id,
            )
            session.add(document)
            session.flush()
            statement.status = "confirmed"
            statement.base_amount = Decimal("0")
            statement.fee_amount = Decimal("0")
            statement.upstream_contract_ids = [facts["upstream_id"]]
            statement.stamped_document_id = document.id
            statement.confirmed_at = datetime.now(UTC)
            statement.confirmed_by = actor.id
            session.commit()
            facts.update(actor_id=actor.id, version=statement.version)
            facts["schema"] = schema
        yield engine, facts
    finally:
        engine.dispose()
        # schema is a fixture-generated constant, never a caller-supplied name.
        assert re.fullmatch(r"fee_race_[0-9a-f]{32}", schema)
        with admin.begin() as connection:
            connection.execute(text(f'DROP SCHEMA "{schema}" CASCADE'))
        admin.dispose()


@pytest.mark.parametrize("same_key", [True, False])
def test_concurrent_corrections_commit_once_and_replay_or_conflict(
    isolated_fee_database, same_key
):
    engine, facts = isolated_fee_database
    scope = EffectivePartyScope(
        user_id=facts["actor_id"],
        source="explicit",
        scope_mode="owner",
        owner_party_ids=[facts["owner_id"]],
    )
    request = ManagementFeeSuccessorRequest(
        expected_version=facts["version"], reason="并发更正验证"
    )
    keys = [str(uuid4()), str(uuid4())]
    if same_key:
        keys[1] = keys[0]

    def correct(key):
        with Session(engine, expire_on_commit=False) as session:
            try:
                result = asyncio.run(
                    management_fee_confirmation_service.supersede(
                        AsyncSessionFacade(session),
                        statement_id=facts["statement_id"],
                        request=request,
                        actor_id=facts["actor_id"],
                        scope=scope,
                        idempotency_key=key,
                    )
                )
                return result
            except Exception as error:
                session.rollback()
                return error

    with Session(engine) as blocker, ThreadPoolExecutor(max_workers=2) as workers:
        blocker.scalar(
            select(Party).where(Party.id == facts["owner_id"]).with_for_update()
        )
        blocker_pid = blocker.scalar(text("SELECT pg_backend_pid()"))
        futures = [workers.submit(correct, key) for key in keys]
        deadline = time.monotonic() + 15
        observed_waiters = 0
        try:
            with engine.connect() as monitor:
                while time.monotonic() < deadline:
                    # Both independent sessions must actually wait on PostgreSQL.
                    monitor.commit()
                    observed_waiters = monitor.scalar(
                        text(
                            "SELECT count(*) FROM pg_stat_activity "
                            "WHERE application_name = :application "
                            "AND wait_event_type = 'Lock' "
                            "AND cardinality(pg_blocking_pids(pid)) > 0 "
                            "AND pid <> :blocker"
                        ),
                        {"application": facts["schema"], "blocker": blocker_pid},
                    )
                    if observed_waiters == 2:
                        break
                    if any(future.done() for future in futures):
                        break
                    time.sleep(0.01)
        finally:
            blocker.rollback()
        results = [future.result(timeout=20) for future in futures]
    assert observed_waiters == 2, results
    successes = [result for result in results if not isinstance(result, Exception)]
    failures = [result for result in results if isinstance(result, Exception)]
    if same_key:
        assert not failures, failures
        assert sorted(result.idempotent for result in successes) == [False, True]
        assert len({result.successor_statement_id for result in successes}) == 1
    else:
        assert len(successes) == len(failures) == 1, results
        assert failures[0].code == "VERSION_CONFLICT"
    # A fresh connection sees durable writes, not a shared savepoint transaction.
    with Session(engine) as verifier:
        assert (
            verifier.scalar(select(func.count()).select_from(ManagementFeeStatement))
            == 2
        )
        assert (
            verifier.scalar(select(func.count()).select_from(AssetContractWriteReceipt))
            == 1
        )
        assert (
            verifier.scalar(select(func.count()).select_from(BusinessChangeEvent)) == 1
        )
        original = verifier.get(ManagementFeeStatement, facts["statement_id"])
        assert original.status == "superseded"
        assert original.successor_statement_id == successes[0].successor_statement_id


@pytest.mark.parametrize("first_action", ["receipt", "confirm"])
def test_confirmation_and_receipt_serialize_without_partial_writes(
    isolated_fee_database, first_action
):
    engine, facts = isolated_fee_database
    with Session(engine) as seed:
        statement = seed.get(ManagementFeeStatement, facts["statement_id"])
        statement.status = None
        statement.base_amount = statement.fee_amount = None
        statement.upstream_contract_ids = None
        statement.confirmed_at = statement.confirmed_by = None
        seed.add(
            ManagementFeeDeferral(
                statement_id=statement.id,
                rent_ledger_entry_id=facts["entry_id"],
                reason="待核余款",
                created_by=facts["actor_id"],
            )
        )
        seed.commit()
        version = statement.version
    scope = EffectivePartyScope(
        user_id=facts["actor_id"],
        source="explicit",
        scope_mode="owner",
        owner_party_ids=[facts["owner_id"]],
    )
    ready, release = Event(), Event()

    class HoldingCommitFacade(AsyncSessionFacade):
        async def commit(self):
            ready.set()
            assert release.wait(20), "First transaction was not released"
            await super().commit()

    def command(action, hold=False):
        with Session(engine, expire_on_commit=False) as session:
            facade = (
                HoldingCommitFacade(session) if hold else AsyncSessionFacade(session)
            )
            arguments = dict(
                statement_id=facts["statement_id"],
                actor_id=facts["actor_id"],
                scope=scope,
                idempotency_key=f"race-{action}-{uuid4()}",
            )
            try:
                if action == "confirm":
                    return asyncio.run(
                        management_fee_confirmation_service.confirm(
                            facade,
                            request=ManagementFeeConfirmationRequest(
                                expected_version=version
                            ),
                            **arguments,
                        )
                    )
                return asyncio.run(
                    management_fee_owner_receipt_service.register(
                        facade,
                        request=ManagementFeeOwnerReceiptRequest(
                            rent_ledger_entry_id=facts["entry_id"],
                            amount=Decimal("40"),
                            occurred_on=facts["effective_date"],
                            expected_version=1,
                        ),
                        **arguments,
                    )
                )
            except Exception as error:
                session.rollback()
                return error

    with ThreadPoolExecutor(max_workers=2) as workers:
        first = workers.submit(command, first_action, True)
        second = None
        waited = False
        try:
            assert ready.wait(15), (
                first.result(timeout=1)
                if first.done()
                else "First transaction did not reach commit"
            )
            second = workers.submit(
                command, "confirm" if first_action == "receipt" else "receipt"
            )
            deadline = time.monotonic() + 15
            with engine.connect() as monitor:
                while time.monotonic() < deadline:
                    monitor.commit()
                    waited = (
                        monitor.scalar(
                            text(
                                "SELECT count(*) FROM pg_stat_activity WHERE application_name = :app "
                                "AND wait_event_type = 'Lock' AND cardinality(pg_blocking_pids(pid)) > 0"
                            ),
                            {"app": facts["schema"]},
                        )
                        == 1
                    )
                    if waited or second.done():
                        break
                    time.sleep(0.01)
        finally:
            release.set()
        winner = first.result(timeout=20)
        loser = second.result(timeout=20) if second is not None else None
    assert waited, (winner, loser)
    assert not isinstance(winner, Exception), winner
    assert isinstance(loser, Exception), loser
    assert loser.code == (
        "VERSION_CONFLICT"
        if first_action == "receipt"
        else "MANAGEMENT_FEE_STATEMENT_LOCKED"
    )
    with Session(engine) as verifier:
        original = verifier.get(ManagementFeeStatement, facts["statement_id"])
        records = verifier.scalars(select(RentPaymentRecord)).all()
        snapshots = verifier.scalars(select(ManagementFeeStatementLine)).all()
        receipts = verifier.scalars(select(AssetContractWriteReceipt)).all()
        audits = verifier.scalars(select(BusinessChangeEvent)).all()
        statements = verifier.scalars(select(ManagementFeeStatement)).all()
        assert len(audits) == 1
        if first_action == "receipt":
            assert len(statements) == 1
            assert original.status is None
            assert len(records) == 1 and records[0].amount == Decimal("40")
            assert not snapshots and not receipts
            assert original.version > version
            assert audits[0].action == "rent_payment_registered"
        else:
            assert len(statements) == 2
            following = next(row for row in statements if row.id != original.id)
            assert following.status is None and following.version == 1
            assert following.period > original.period
            assert original.status == "confirmed"
            assert original.fee_amount == Decimal("0")
            assert not records
            assert len(snapshots) == len(receipts) == 1
            assert snapshots[0].owner_received_amount == Decimal("0")
            assert snapshots[0].deferred_amount == Decimal("100")
            assert snapshots[0].counted_record_ids == []
            assert audits[0].action == "confirm_management_fee_statement"
